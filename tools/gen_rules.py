#!/usr/bin/env python3
"""Generate Prometheus SLO rules from slo/slos.yaml.

For every SLO this emits:
  * slo:sli_error:ratio_rate<W>   error ratio for each window W used by the burn policy (+ the SLO window)
  * slo:error_budget:ratio        the budget as a series, so dashboards never hard-code it
  * slo:error_budget:remaining_ratio
  * one alert per burn-policy row: (long window > N*budget) AND (short window > N*budget)

Usage:
  python tools/gen_rules.py            # (re)write the rules file
  python tools/gen_rules.py --check    # exit 1 if the committed file is stale (CI)
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SPEC = ROOT / "slo" / "slos.yaml"
DEFAULT_OUT = ROOT / "observability" / "prometheus" / "rules" / "slo.rules.yml"

HEADER = (
    "# GENERATED by tools/gen_rules.py from slo/slos.yaml - DO NOT EDIT.\n"
    "# Run `make rules` to regenerate. CI fails on drift.\n"
)
DURATION = re.compile(r"^(\d+)([smhdw])$")
UNIT_SECONDS = {"s": 1, "m": 60, "h": 3600, "d": 86400, "w": 604800}
ANNOT_VALUE = "{{ $value | humanizePercentage }}"  # Prometheus template, emitted verbatim


class SpecError(ValueError):
    pass


def seconds(d: str) -> int:
    m = DURATION.match(d)
    if not m:
        raise SpecError(f"bad duration {d!r} (expected e.g. 5m, 1h, 30d)")
    return int(m.group(1)) * UNIT_SECONDS[m.group(2)]


def num(x: float) -> str:
    return f"{x:.10g}"


def budget(objective_pct: float) -> float:
    if not 0 < objective_pct < 100:
        raise SpecError(f"objective must be in (0,100), got {objective_pct}")
    return round(1 - objective_pct / 100, 10)


def validate(spec: dict) -> None:
    names = set()
    for row in spec["burn_policy"]:
        if seconds(row["short"]) >= seconds(row["long"]):
            raise SpecError(f"policy {row['name']}: short window must be smaller than long window")
        if row["severity"] not in ("page", "ticket"):
            raise SpecError(f"policy {row['name']}: severity must be page|ticket")
        if row["burn_rate"] <= 0:
            raise SpecError(f"policy {row['name']}: burn_rate must be > 0")
        seconds(row["for"])
    for slo in spec["slos"]:
        if slo["name"] in names:
            raise SpecError(f"duplicate slo {slo['name']}")
        names.add(slo["name"])
        budget(slo["objective"])
        seconds(slo["window"])
        sli = slo["sli"]
        if sli["kind"] == "latency":
            if sli["threshold_seconds"] not in sli["buckets"]:
                raise SpecError(
                    f"{slo['name']}: threshold {sli['threshold_seconds']}s is not a histogram bucket "
                    f"{sli['buckets']}; the 'good events' count would be wrong"
                )
        elif sli["kind"] != "availability":
            raise SpecError(f"{slo['name']}: unknown sli kind {sli['kind']!r}")


def error_ratio_expr(sli: dict, window: str) -> str:
    sel, m = sli["selector"], sli["metric"]
    if sli["kind"] == "availability":
        errs = f"{m}{{{sel},{sli['error_matcher']}}}"
        total = f"{m}{{{sel}}}"
        # `or vector(0)`: if no 5xx series exists yet the numerator is EMPTY (not 0),
        # the division returns nothing and alerts/dashboards go blank. This keeps it at 0.
        return f"(sum(rate({errs}[{window}])) or vector(0))\n/\nsum(rate({total}[{window}]))"
    good = f'{m}_bucket{{{sel},le="{num(sli["threshold_seconds"])}"}}'
    total = f"{m}_count{{{sel}}}"
    return f"1 - (\n  sum(rate({good}[{window}]))\n  /\n  sum(rate({total}[{window}]))\n)"


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join(pad + line for line in text.split("\n"))


def generate(spec: dict) -> str:
    validate(spec)
    policy = spec["burn_policy"]
    out = [HEADER, "groups:"]
    for slo in spec["slos"]:
        name, sli = slo["name"], slo["sli"]
        b = budget(slo["objective"])
        windows = sorted(
            {r["long"] for r in policy} | {r["short"] for r in policy} | {slo["window"]}, key=seconds
        )
        out.append(f"  - name: slo-{name}-recordings")
        out.append("    rules:")
        for w in windows:
            out += [
                f"      - record: slo:sli_error:ratio_rate{w}",
                "        expr: |",
                block(error_ratio_expr(sli, w), 10),
                "        labels:",
                f"          slo: {name}",
            ]
        out += [
            "      - record: slo:error_budget:ratio",
            f"        expr: vector({num(b)})",
            "        labels:",
            f"          slo: {name}",
            "      - record: slo:error_budget:remaining_ratio",
            "        expr: |",
            f'          1 - (slo:sli_error:ratio_rate{slo["window"]}{{slo="{name}"}} / slo:error_budget:ratio{{slo="{name}"}})',
            "        labels:",
            f"          slo: {name}",
        ]
        out.append(f"  - name: slo-{name}-alerts")
        out.append("    rules:")
        window_hours = seconds(slo["window"]) / 3600
        for r in policy:
            thr = f"({num(r['burn_rate'])} * {num(b)})"
            alert = "SLOBurn" + r["name"].capitalize()
            hours = window_hours / r["burn_rate"]
            exhaust = f"{hours:.0f}h" if hours < 48 else f"{hours / 24:.1f}d"
            sel = f'{{slo="{name}"}}'
            out += [
                f"      - alert: {alert}",
                "        expr: |",
                f"          slo:sli_error:ratio_rate{r['long']}{sel} > {thr}",
                "          and",
                f"          slo:sli_error:ratio_rate{r['short']}{sel} > {thr}",
                f"        for: {r['for']}",
                "        labels:",
                f"          severity: {r['severity']}",
                f"          slo: {name}",  # explicit: also keeps promtool lint from flagging cross-SLO duplicates
                "        annotations:",
                f"          summary: '{name}: burning error budget {num(r['burn_rate'])}x too fast ({r['severity']})'",
                "          description: '"
                f"Error ratio over {r['long']} is {ANNOT_VALUE} (budget {b * 100:.3g}%). "
                f"At this rate the {slo['window']} budget is gone in about {exhaust}. "
                f"Runbook: docs/runbook.md#{name}'",
            ]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", type=pathlib.Path, default=DEFAULT_SPEC)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if --out differs from generated output")
    args = ap.parse_args()
    try:
        text = generate(yaml.safe_load(args.spec.read_text()))
    except (SpecError, KeyError) as e:
        print(f"spec error: {e}", file=sys.stderr)
        return 2
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            print(f"{args.out} is stale: run `make rules` and commit the result", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
